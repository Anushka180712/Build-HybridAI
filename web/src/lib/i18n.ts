export function translate(text: string, lang: UiLang): string {
  if (lang === 'en') return text;
  return T[text]?.[COL[lang]] ?? text;
}

/** `t('Check it')` in the chosen language, falling back to English. */
export function useT(): ((text: string) => string) & { lang: UiLang } {
  const lang = uiLang(settingsStore.use().language);
  return Object.assign((text: string) => translate(text, lang), { lang });
}
