export function translate(text: string, lang: UiLang): string {
  if (lang === 'en') return text;
  const col = COL[lang];
  if (col === undefined) return text;
  const direct = T[text]?.[col];
  if (direct) return direct;
  const normalized = text.replace(/[“”]/g, '"').replace(/[’]/g, "'").trim();
  const normMatch = T[normalized]?.[col];
  if (normMatch) return normMatch;
  if (normalized.toLowerCase().startsWith('scam wave:') && normalized.toLowerCase().includes('electricity')) {
    const key = 'Scam wave: fake electricity-bill and KYC "update" texts are spiking. Never pay or share an OTP through a texted link.';
    return T[key]?.[col] ?? text;
  }
  const m = normalized.match(/^On-device checks took ([\d.]+) s on average, with nothing sent anywhere\.$/i);
  if (m) {
    const s = m[1];
    const templates = [
      `डिवाइस पर जाँच में औसतन ${s} सेकंड लगे, और कुछ भी कहीं नहीं भेजा गया।`,
      `ডিভাইসে যাচাইয়ে গড়ে ${s} সেকেন্ড সময় লেগেছে, কোথাও কিছু পাঠানো হয়নি।`,
      `சாதனச் சரிபார்ப்புக்கு சராசரியாக ${s} வினாடிகள் ஆனது, எங்கும் எதுவும் அனுப்பப்படவில்லை.`,
      `పరికరంలో తనిఖీకి సగటున ${s} సెకన్లు పట్టింది, ఎక్కడికీ ఏమీ పంపలేదు.`,
      `डिव्हाइसवरील तपासणीला सरासरी ${s} सेकंद लागले, काहीही कुठेही पाठवले नाही.`,
    ];
    return templates[col] ?? text;
  }
  return text;
}

/** `t('Check it')` in the chosen language, falling back to English. */
export function useT(): ((text: string) => string) & { lang: UiLang } {
  const lang = uiLang(settingsStore.use().language);
  return Object.assign((text: string) => translate(text, lang), { lang });
}
